// Writes docs/subpage-copy-draft.md from content/**.json so the SEO specialist
// can review every draft page in one readable document. Generated, not edited.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const contentDir = join(root, 'content');
const routes = { features: '/features/', channels: '/channels/', 'use-cases': '/use-cases/', industries: '/industries/' };

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith('.json')) files.push(path);
  }
})(contentDir);

function routeOf(file, data) {
  const [folder, name] = relative(contentDir, file).split(/[\\/]/);
  if (routes[folder]) return `${routes[folder]}${data.slug}/`;
  if (folder === 'hubs') return `/${name.replace('.json', '')}/`;
  return `/${name.replace('.json', '')}/`;
}

const label = key => key.replace(/([A-Z])/g, ' $1').replace(/^./, c => c.toUpperCase());
const skip = new Set(['status', 'source', 'kind', 'slug', 'card', 'built', 'href', 'featured']);

function render(value, depth) {
  if (typeof value === 'string') return [value];
  if (Array.isArray(value)) return value.flatMap(v => typeof v === 'string' ? [`- ${v}`] : [...render(v, depth), '']);
  const out = [];
  for (const [key, v] of Object.entries(value)) {
    if (skip.has(key)) continue;
    if (typeof v === 'string') out.push(`**${label(key)}:** ${v}`, '');
    else out.push(`${'#'.repeat(Math.min(depth, 6))} ${label(key)}`, '', ...render(v, depth + 1), '');
  }
  return out;
}

const pages = files.map(file => { const data = JSON.parse(readFileSync(file, 'utf8')); return { route: routeOf(file, data), data }; });
const lines = [
  '# Subpage copy: drafts for review',
  '',
  `Generated by \`npm run export:copy\` from \`content/**\`. ${pages.length} pages. Every page is a draft pending the SEO specialist's final copy. Edit the JSON files, not this document.`,
  '',
  ...pages.map(p => `- ${p.route} (${p.data.kind})`),
  '',
];
for (const { route, data } of pages) lines.push('---', '', `## ${route}`, '', `Status: ${data.status}, ${data.source}`, '', ...render(data, 3), '');
writeFileSync(join(root, 'docs', 'subpage-copy-draft.md'), lines.join('\n').replace(/\n{3,}/g, '\n\n'));
console.log(`Wrote docs/subpage-copy-draft.md with ${pages.length} pages.`);
